// Deterministic pseudo random generator so demo data is reproducible
function rng(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 0x100000000;
  };
}

function pointIn(room: Room, rand: () => number, W = 1600, H = 1000) {
  const x = room.x + 40 + rand() * (room.w - 80);
  const y = room.y + 40 + rand() * (room.h - 80);
  return { map_x: +(x / W).toFixed(4), map_y: +(y / H).toFixed(4) };
}

function dateOffset(days: number) {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() + Math.round(days));
  return d.toISOString().slice(0, 10);
}

function mac(rand: () => number) {
  return Array.from({ length: 6 }, (_, i) => (i === 0 ? 0x00 : Math.floor(rand() * 256)).toString(16).padStart(2, '0')).join(':');
}

